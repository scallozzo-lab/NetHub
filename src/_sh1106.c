void SH1106_drawChar(uint8_t page, uint8_t col, char c)
{
    if (c < 32 || c > 126) c = '?';  // Caracter inválido

    uint16_t index = (c - 32) * 5;   // 5 bytes por carácter

    // Selecciona página
    SH1106_sendCommand(0xB0 + page);

    // Ajusta columna + offset del SH1106
    SH1106_sendCommand((col + 2) & 0x0F);          // low col
    SH1106_sendCommand(0x10 | ((col + 2) >> 4));   // high col

    // Comienza escritura de datos
    I2C_start();
    I2C_writeByte((_i2caddr /*<< 1*/) | 0);
    I2C_writeByte(0x40); // DATA

    // Enviar los 5 bytes del carácter
    for (uint8_t i = 0; i < 5; i++)
    {
        I2C_writeByte(font5x7[index + i]);
    }

    // Espacio entre caracteres
    I2C_writeByte(0x00);

    I2C_stop();
}

void SH1106_print(uint8_t page, uint8_t col, const char *str)
{
    while (*str)
    {
        SH1106_drawChar(page, col, *str++);
        col += 6; // 5 pix + 1 espacio
        if (col > 122) break;  // evita overflow
    }
}


void SH1106_drawChar8x8(uint8_t page, uint8_t col, char c)
{
    if (c < 32 || c > 126)
        c = '?';   // Caracter inválido → reemplazar

    const uint8_t *glyph = font8x8[c - 32];

    /*
        Notas:
        - Cada página del SH1106 es 8 pix de altura.
        - Un font de 8×8 encaja EXACTO en una sola página.
        - Cada byte = columna vertical de 8 bits.
        - Por lo tanto, se dibuja como 8 bytes en horizontal.
    */

    // Página
    SH1106_sendCommand(0xB0 + page);

    // Columna baja y alta (con offset de 2)
    uint8_t realCol = col + 2;

    SH1106_sendCommand(realCol & 0x0F);            // low column
    SH1106_sendCommand(0x10 | (realCol >> 4));     // high column

    // Enviar los 8 bytes del carácter
    I2C_start();
    I2C_writeByte((_i2caddr /*<< 1*/) | 0);  // Write
    I2C_writeByte(0x40); // DATA mode

    for (uint8_t i = 0; i < 8; i++)
        I2C_writeByte(glyph[i]);

    I2C_stop();
}

void SH1106_print8x8(uint8_t page, uint8_t col, const char *str)
{
    while (*str)
    {
        SH1106_drawChar8x8(page, col, *str++);
        col += 8;      // 8 pix por carácter
        if (col > 120) // evita overflow
            break;
    }
}

void SH1106_SetCursor(uint8_t x, uint8_t page)
{
    uint8_t col = x + 2;  // SH1106 offset

    SH1106_sendCommand(0xB0 | page);                 // Set page address
    SH1106_sendCommand(0x10 | (col >> 4));           // Set high nibble of column
    SH1106_sendCommand(0x00 | (col & 0x0F));         // Set low nibble of column
}

void SH1106_SendDataBlock(const uint8_t *data, uint16_t len)
{
    I2C_start();
    I2C_write((_i2caddr /*<< 1*/) | 0);  // Write mode
    I2C_write(0x40);                    // Data mode

    while (len--)
        I2C_write(*data++);

    I2C_stop();
}

void SH1106_DrawBitmap(uint8_t x, uint8_t page, 
                       const uint8_t *bmp,
                       uint8_t w, uint8_t h)
{
    uint8_t pages = h / 8;
    uint16_t index = 0;

    for (uint8_t col = 0; col < w; col++)
    {
        for (uint8_t p = 0; p < pages; p++)
        {
            SH1106_SetCursor(x + col, page + p);
            SH1106_SendData(bmp[index++]);
        }
    }
}

void SH1106_Printf(uint8_t font, uint8_t x, uint8_t page, const char *fmt, ...)
{
    char buffer[64];

    va_list args;
    va_start(args, fmt);
    vsnprintf(buffer, sizeof(buffer), fmt, args);
    va_end(args);

    switch(font)
    {
        case _FONT_5X7:
        SH1106_print(x, page, buffer);
        break;

        case _FONT_8X8:
        SH1106_print8x8(x, page, buffer);
        break;    
    }
}